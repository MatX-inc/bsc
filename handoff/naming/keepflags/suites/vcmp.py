# usage: python3 -I vcmp.py <a.v> <b.v> [-v]
# classifies the difference between two bsc-generated Verilog files:
#   identical      byte-identical apart from the date/version header
#   renumbered     identical once generated-name numbers are normalised
#   added-wires    same canonical sinks (outputs, next-state, instance
#                  connections, system tasks) after inlining internal nets,
#                  and b only adds net names
#   names-only     same canonical sinks, and some names of a are gone in b
#   structural     canonical sinks differ (listed with -v)
#   unparsed       the canonicaliser could not parse one side
import re, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vcanon, vnames

HDR = re.compile(r'^// (On |Generated by )')
NUM = re.compile(r'(__h|___d|_d|__q|_q)\d+')

def strip(t):
    return '\n'.join(l for l in t.split('\n') if not HDR.match(l))

def classify(pa, pb, verbose=False):
    ta = strip(open(pa, errors='replace').read())
    tb = strip(open(pb, errors='replace').read())
    if ta == tb:
        return 'identical', []
    if NUM.sub(r'\1N', ta) == NUM.sub(r'\1N', tb):
        return 'renumbered', []
    try:
        ma = {M['name']: M for M in vcanon.load(pa)}
        mb = {M['name']: M for M in vcanon.load(pb)}
    except vcanon.ParseError as e:
        return 'unparsed', [str(e)]
    except RecursionError:
        return 'unparsed', ['recursion']
    if set(ma) != set(mb):
        return 'structural', ['module sets differ']
    notes = []
    struct = False
    lost_any = False
    for name in sorted(ma):
        try:
            ka, sa, Ca, Sa = vcanon.module_keys(ma[name])
            kb, sb, Cb, Sb = vcanon.module_keys(mb[name])
        except vcanon.ParseError as e:
            return 'unparsed', ['%s: %s' % (name, e)]
        except RecursionError:
            return 'unparsed', ['recursion']
        if sa != sb:
            struct = True
            notes.append('%s: port signature differs' % name)
        for k in sorted(set(ka) | set(kb), key=str):
            if ka.get(k) != kb.get(k):
                struct = True
                if verbose:
                    def sh(C, S):
                        h = S.get(k)
                        if h is None:
                            return 'ABSENT'
                        if isinstance(h, int):
                            return C.show(h, maxd=int(os.environ.get('MAXD', '8')))
                        return str(h)[:300]
                    notes.append('%s %s\n      A: %s\n      B: %s' % (name, k, sh(Ca, Sa), sh(Cb, Sb)))
                else:
                    notes.append('%s %s' % (name, k))
    if struct:
        return 'structural', notes
    na = vnames.modules(pa)
    nb = vnames.modules(pb)
    for name in na:
        if set(na[name]) - set(nb.get(name, {})):
            lost_any = True
    return ('names-only' if lost_any else 'added-wires'), notes

if __name__ == '__main__':
    c, notes = classify(sys.argv[1], sys.argv[2], '-v' in sys.argv)
    print(c)
    for n in notes[:int(os.environ.get('MAXN', '40'))]:
        print('   ', n)
