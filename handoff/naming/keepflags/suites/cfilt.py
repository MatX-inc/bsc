# usage: python3 -I cfilt.py <a.cxx> <b.cxx> : prints the two files' lines left after dropping
# header/date lines, VCD and symbol bookkeeping lines, and every line naming an identifier that
# exists in only one of the files (unified diff of the remainder)
import re, sys, difflib
ID = re.compile(r'[A-Za-z_][A-Za-z0-9_]*')
BOOK = re.compile(r'init_symbol|symbol_count|vcd_|\+\+num|SYM_DEF|SYM_PORT|SYM_MODULE|SYM_RULE|^\s*[{}]\s*$|^\s*"[^"]*",\s*$|^\s*\d+u\);\s*$|^\s*&\w+,\s*$|^// (On|Generated by)|^\s*$')
def lines(p):
    return open(p, errors='replace').read().split('\n')
a, b = lines(sys.argv[1]), lines(sys.argv[2])
ia = set(x for l in a for x in ID.findall(l)); ib = set(x for l in b for x in ID.findall(l))
only = (ia - ib) | (ib - ia)
def keep(l):
    if BOOK.search(l): return False
    return not any(x in only for x in ID.findall(l))
fa = [l for l in a if keep(l)]; fb = [l for l in b if keep(l)]
d = list(difflib.unified_diff(fa, fb, lineterm='', n=0))
print('only-in-a:', len(ia - ib), 'only-in-b:', len(ib - ia), 'residual diff lines:', sum(1 for l in d if l[:1] in '+-' and not l.startswith(('+++', '---'))))
if '-v' in sys.argv:
    print('\n'.join(d[:200]))
